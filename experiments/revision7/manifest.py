"""Revision-7 manifest: adds the revision-7 outputs to results/MANIFEST.md and results/manifest.json.

    python -m experiments.revision7.manifest

Entries of earlier revisions are kept exactly as they are; earlier revision-7 entries are replaced.
"""

from __future__ import annotations

import hashlib
import json

from common.config import PROJECT_ROOT

R = PROJECT_ROOT / "results"
R7 = "results/revision7/"
VE5 = "results/revision5/veins/veins_rows.jsonl"
VE6 = "results/revision6/veins/veins6_rows.jsonl"
SUMO5 = [f"results/revision5/runs/{k}__EVAL__headline__default__sumo.csv" for k in ("classical", "rule", "agent")]
V = "experiments/revision7/veins/"
A = "experiments/revision7/analysis/"
SPEC = [
    (R7 + "veins/app_gate.json", V + "validate7.py", "python -m experiments.revision7.veins.validate7 gate",
     [R7 + "veins/raw/r7_gate/"]),
    (R7 + "veins/port_validation_policy_unit.json", V + "validate7.py", "python -m experiments.revision7.veins.validate7 unit", []),
    (R7 + "veins/port_validation_policy_trace.json", V + "validate7.py", "python -m experiments.revision7.veins.validate7 gate",
     [R7 + "veins/raw/r7_gate_capped/"]),
    (R7 + "veins/capped_rows.jsonl", V + "score7.py", "python -m experiments.revision7.veins.score7 capped",
     [R7 + "veins/raw/r7_capped/ (from queue7 capped)"]),
    (R7 + "veins/d9_rows.jsonl", V + "score7.py", "python -m experiments.revision7.veins.score7 d9",
     [R7 + "veins/raw/r7_d9/ (from queue7 d9)"]),
    (R7 + "runs/custom_capped_rows.jsonl", "experiments/revision7/custom_cap.py", "python -m experiments.revision7.custom_cap --jobs 3",
     ["SUMO trace cache"]),
    (R7 + "analysis/exp_a.json", A + "exp_a.py", None, [R7 + "veins/capped_rows.jsonl", R7 + "runs/custom_capped_rows.jsonl", VE5, VE6] + SUMO5),
    (R7 + "analysis/exp_b.json", A + "exp_b.py", None, [R7 + "veins/d9_rows.jsonl", VE5, VE6, "results/revision6/analysis/veins_methods.json"]),
]
MARK = "## Revision 7"


def main(argv=None) -> int:
    man = json.loads((R / "manifest.json").read_text(encoding="utf-8"))
    keep = [o for o in man["outputs"] if not o["output"].startswith(R7)]
    new = []
    for name, script, cmd, src in SPEC:
        p = PROJECT_ROOT / name
        pv = {}
        if p.suffix == ".json":
            pv = json.loads(p.read_text(encoding="utf-8")).get("provenance", {}) or {}
        new.append({"output": name, "exists": p.exists(), "script": script, "command": cmd or pv.get("command"),
                    "commit": pv.get("git_commit"), "config_hash": pv.get("config_hash"), "generated": pv.get("generated"),
                    "sources": src, "sha256": hashlib.sha256(p.read_bytes()).hexdigest()})
    man["outputs"] = keep + new
    (R / "manifest.json").write_text(json.dumps(man, indent=1) + "\n", encoding="utf-8", newline="\n")
    text = (R / "MANIFEST.md").read_text(encoding="utf-8").split(MARK)[0].rstrip() + "\n\n"
    lines = [MARK, "", "Generated by `python -m experiments.revision7.manifest`. Regenerate with `reproduce_revision7.ps1` (or `.sh`). The",
             "scored rows and the raw OMNeT++ outputs (`results/revision7/veins/raw/`) are committed; the decision-server logs",
             "(`D:\\aiharp-r7-bridge-logs`, 902 MB) are not.", "",
             "| Output | Script / command | Commit | Config hash | Source rows |", "|---|---|---|---|---|"]
    for o in new:
        src = "<br>".join(f"`{s}`" for s in o["sources"]) or "–"
        lines.append(f"| `{o['output']}` | `{o['command']}` | {(o['commit'] or '–')[:12]} | {o['config_hash'] or '–'} | {src} |")
    (R / "MANIFEST.md").write_text(text + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(R / "MANIFEST.md")
    print(R / "manifest.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
