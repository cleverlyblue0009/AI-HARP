"""Stage D: regenerated and new figures, into results/revision1/D/.

::

    python -m experiments.revision1.stage_d

* D1 -- paper Fig. 8 (repo fig03_regret_margin: regret/margin per cell, mostly
  empty bars) as a CSV + LaTeX table, from the same agent_evaluation.json.
* D2 -- fig03 with readable x labels; Fig. 14 (repo fig09) with the agent's
  tau arms separated and non-colliding point labels.
* D3 -- Fig. 12 (repo fig06) with the annotation naming the peak multiplier's
  group and update (A5).
* D4 -- latency-bounded vs unbounded matched cost in the headline cells (B1).

Uses the same plotting functions as analysis/report.py (so reproduce.sh
regenerates the corrected versions into results/figures/); only the output
directory differs, so the committed figures are not overwritten here.
"""

from __future__ import annotations

import json

import numpy as np
import pandas as pd

from analysis import figures as F
from common.config import PROJECT_ROOT
from experiments.revision1.provenance import out_dir, stamp, write_json

R = PROJECT_ROOT / "results"


def d1_table(d) -> None:
    rows = []
    for mode in ("sampled", "argmax"):
        ev = json.loads((R / "agent_ref" / mode / "agent_evaluation.json").read_text())
        for axis in ("cost", "tir_median_s"):
            a = ev["axes"][axis]
            for cell, v in a["per_cell"].items():
                fin = lambda x: float(x) if x is not None and np.isfinite(x) else None  # noqa: E731
                rows.append({"policy_mode": mode, "tau": ev["tau"], "axis": axis, "cell": cell,
                             "agent": fin(v["agent"]), "oracle_policy": v["oracle_policy"],
                             "oracle": fin(v["oracle"]), "fixed_best": a["fixed_best"],
                             "fixed": fin(v["fixed"]), "regret": fin(v["regret"]),
                             "margin": fin(v["margin"]),
                             "status": "matched" if np.isfinite(v["agent"]) else "never matched"})
    df = pd.DataFrame(rows)
    df.to_csv(d / "table_fig8_regret_margin.csv", index=False)
    sub = df[(df.policy_mode == "sampled")]
    lines = ["% Paper Fig. 8 as a table (revision-1 D1). Reference agent, tau=0.5, sampled,",
             "% eval seeds 0-9. Source: results/agent_ref/sampled/agent_evaluation.json.",
             "% Generated by experiments/revision1/stage_d.py -- do not edit by hand.",
             r"\begin{tabular}{llrlrrrr}", r"\toprule",
             r"Axis & Cell & Agent & Oracle-best & Oracle & Fixed & Regret & Margin \\", r"\midrule"]
    for _, r in sub.iterrows():
        f = lambda x, p=False: "--" if x is None or (isinstance(x, float) and not np.isfinite(x)) \
            else (f"${100 * x:+.1f}\\%$" if p else f"${x:.3f}$")  # noqa: E731
        cell = r.cell.replace("_highway", "").replace("/clear/fog_bank", "").replace("_", r"\_")
        ax = "cost" if r.axis == "cost" else "TIR$_{50}$ (s)"
        agent = f(r.agent) if r.status == "matched" else "never"
        lines.append(f"{ax} & {cell} & {agent} & {r.oracle_policy.replace('_', ' ')} & {f(r.oracle)} "
                     f"& {f(r.fixed)} & {f(r.regret, True)} & {f(r.margin, True)} \\\\")
    fixed = sub.drop_duplicates("axis").set_index("axis").fixed_best.to_dict()
    lines += [r"\midrule",
              r"\multicolumn{8}{l}{\footnotesize Best fixed: cost axis " +
              fixed["cost"].replace("_", r"\_") + "; TIR axis " +
              fixed["tir_median_s"].replace("_", r"\_") + r".} \\", r"\bottomrule", r"\end{tabular}"]
    (d / "table_fig8_regret_margin.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def d2_d3_figures(d) -> list[str]:
    from analysis.report import _flooding_note, _lambda_cap, load_runs_current

    F.FIG_DIR = d                      # save() reads the module global at call time
    made = []
    ev = json.loads((R / "agent_ref" / "sampled" / "agent_evaluation.json").read_text())
    F.fig_regret_margin(ev["axes"]["cost"]["per_cell"], name="fig08_paper_regret_margin_fixed")
    made.append("fig08_paper_regret_margin_fixed")
    df = load_runs_current()
    F.fig_latency_cost_inversion(df, "rural_highway", 20.0, note=_flooding_note(df),
                                 name="fig14_paper_latency_cost_fixed")
    made.append("fig14_paper_latency_cost_fixed")
    hist = PROJECT_ROOT / "checkpoints" / "campaign" / "ref" / "history.jsonl"
    if hist.exists():
        rows = [json.loads(ln) for ln in hist.read_text().splitlines() if ln.strip()]
        F.fig_training_constraint(rows, lambda_cap=_lambda_cap(), name="fig12_paper_training_fixed")
        made.append("fig12_paper_training_fixed")
    return made


def d4_latency_figure(d, tag: str = "headline") -> str | None:
    p = R / "revision1" / "B1" / f"b1_{tag}.json"
    if not p.exists():
        return None
    import matplotlib.pyplot as plt

    F.apply_ieee_style()
    res = json.loads(p.read_text())["results"]["fixed"]
    bounds = ["unbounded", "D=2s", "D=1.5s", "D=1s", "D=0.5s", "D=derived"]
    xl = ["none", "2.0", "1.5", "1.0", "0.5", "derived"]
    cells = list(res["unbounded"]["cells"])
    fig, axes = plt.subplots(1, len(cells), figsize=(F.DOUBLE_COL, F.DOUBLE_COL * 0.30))
    series = (("oracle_cost", "per-cell oracle-best", F.PALETTE[0], "o", "-"),
              ("fixed_cost", "best single fixed", F.PALETTE[1], "s", "--"),
              ("agent_cost", "AI-HARP (tau=0.5)", F.PALETTE[2], "^", ":"))
    for ax, cell in zip(np.atleast_1d(axes), cells):
        x = np.arange(len(bounds))
        for key, lab, col, m, ls in series:
            y = np.array([res[b]["cells"][cell].get(key) or np.nan for b in bounds], dtype=float)
            ax.plot(x, y, color=col, marker=m, linestyle=ls, ms=3, lw=0.9, label=lab)
            for i in np.flatnonzero(~np.isfinite(y)):
                if key == "agent_cost":
                    ax.annotate("x", (i, 0), xycoords=("data", "axes fraction"), ha="center",
                                va="bottom", fontsize=6, color=col)
        der = res["D=derived"]["cells"][cell]["D_s"]
        ax.set_xticks(x, xl, fontsize=6)
        ax.set_title(cell.replace("_highway", "").replace("/clear/fog_bank", "").replace("_", " ")
                     + f"\n(derived D = {der:.2f} s)", fontsize=6.5, pad=2)
        ax.set_xlabel("median-TIR bound D (s)", fontsize=6)
        ax.tick_params(labelsize=6)
    np.atleast_1d(axes)[0].set_ylabel("Tx per at-risk informed\nat matched coverage", fontsize=6.5)
    np.atleast_1d(axes)[0].legend(fontsize=5.5, loc="upper left")
    fig.text(0.5, -0.02, "x at the bottom = AI-HARP never reaches the target in that cell; "
             "q* held at the unbounded value", ha="center", fontsize=5.5, color=F.GREY)
    fig.tight_layout()
    name = f"fig_d4_latency_bounded_{tag}"
    F.save(fig, name, out_dir=d)
    plt.close(fig)
    return name


def main() -> int:
    d = out_dir("D")
    d1_table(d)
    made = d2_d3_figures(d)
    n = d4_latency_figure(d)
    if n:
        made.append(n)
    write_json(d / "stage_d_meta.json", stamp("D", {"figures": made,
                                                    "tables": ["table_fig8_regret_margin"]}))
    print("made:", made)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
