"""Revision-6 manifest: adds the revision-6 outputs to results/MANIFEST.md and results/manifest.json.

    python -m experiments.revision6.manifest

The revision-5 entries are kept exactly as they are; earlier revision-6 entries are replaced.
"""

from __future__ import annotations

import hashlib
import json

from common.config import PROJECT_ROOT

R = PROJECT_ROOT / "results"
R6 = "results/revision6/"
RO = R6 + "veins/veins6_rows.jsonl"
VE5 = "results/revision5/veins/veins_rows.jsonl"
SUMO5 = [f"results/revision5/runs/{k}__EVAL__headline__default__sumo.csv" for k in ("classical", "rule", "agent")]
A = "experiments/revision6/analysis/"
SPEC = [
    (R6 + "veins/veins6_rows.jsonl", "experiments/revision6/veins/veins6_score.py", "python -m experiments.revision6.veins.veins6_score",
     ["cache/veins_runs/r6/ (replay records, not committed)"]),
    (R6 + "analysis/veins_methods.json", A + "veins_methods.py", None, [RO, VE5] + SUMO5),
    (R6 + "analysis/veins_methods_diagnostics.json", A + "diagnostics.py", None, [RO, VE5] + SUMO5),
    (R6 + "analysis/tables/T-veins-methods.tex", A + "outputs.py", "python -m experiments.revision6.analysis.outputs", [R6 + "analysis/veins_methods.json"]),
    (R6 + "figures/fig_veins_vs_custom.pdf", A + "outputs.py", "python -m experiments.revision6.analysis.outputs", [R6 + "analysis/veins_methods.json"]),
]
MARK = "## Revision 6"


def main(argv=None) -> int:
    man = json.loads((R / "manifest.json").read_text(encoding="utf-8"))
    keep = [o for o in man["outputs"] if not o["output"].startswith(R6)]
    new = []
    for name, script, cmd, src in SPEC:
        p = PROJECT_ROOT / name
        pv = json.loads(p.read_text(encoding="utf-8")).get("provenance", {}) if p.suffix == ".json" else {}
        new.append({"output": name, "exists": p.exists(), "script": script, "command": cmd or pv.get("command"),
                    "commit": pv.get("git_commit"), "config_hash": pv.get("config_hash"), "generated": pv.get("generated"),
                    "sources": src, "sha256": hashlib.sha256(p.read_bytes()).hexdigest()})
    man["outputs"] = keep + new
    (R / "manifest.json").write_text(json.dumps(man, indent=1) + "\n", encoding="utf-8", newline="\n")
    text = (R / "MANIFEST.md").read_text(encoding="utf-8").split(MARK)[0].rstrip() + "\n\n"
    lines = [MARK, "", "Generated by `python -m experiments.revision6.manifest`. Regenerate with `reproduce_revision6.ps1` (or `.sh`). The",
             "scored rows are committed; the replay records they come from are in `cache/`, which is not.", "",
             "| Output | Script / command | Commit | Config hash | Source rows |", "|---|---|---|---|---|"]
    for o in new:
        src = "<br>".join(f"`{s}`" for s in o["sources"])
        lines.append(f"| `{o['output']}` | `{o['command']}` | {(o['commit'] or '–')[:12]} | {o['config_hash'] or '–'} | {src} |")
    (R / "MANIFEST.md").write_text(text + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(R / "MANIFEST.md")
    print(R / "manifest.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
