"""H3: export one (cell, seed) scenario bundle for the Veins replay.

    python -m experiments.revision5.veins.export rural_highway 20 200 [--out cache/veins]

The bundle holds everything Veins needs to replay the custom simulator's run on the SAME SUMO
trace: net/routes/sumocfg as generated by mobility.sumo_runner (identical code path and seed), plus
bundle.json with
  * t0_sumo_s       -- SUMO time of trace step 0 (the warm-up); trace step k <-> SUMO t0 + k*dt;
  * vehicles        -- per trace index: SUMO id and the [first, last] step intervals in which the
                       vehicle is active (in the corridor); Veins nodes outside them are silent;
  * origin          -- the originating vehicle and step (policy-independent: hazard + trace only);
  * comm_range_m    -- the custom PHY's nominal range, used by the distance-based policies so the
                       DECISION rules are identical in both simulators (delivery is what differs);
  * radio           -- the shared nominal physical parameters (phy.yaml).
Identity check: the regenerated SUMO trace must equal the canonical cached trace exactly (positions,
activity, ids); otherwise the bundle is refused.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import shutil
import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np

from common.config import PROJECT_ROOT, load_yaml
from experiments.revision1.provenance import stamp
from experiments.run_sim import RunSpec, run_single
from mobility.generate import get_trace, load_scenario, resolve_backend, trace_cache_key, weather_mobility_factors
from mobility.sumo_runner import BUILD_DIR, generate_sumo_trace

OUT = PROJECT_ROOT / "cache" / "veins"


def intervals(mask: np.ndarray) -> list[list[int]]:
    """[first, last] step runs where mask is True."""
    m = np.concatenate([[False], mask, [False]]).astype(np.int8)
    d = np.diff(m)
    return [[int(a), int(b) - 1] for a, b in zip(np.flatnonzero(d == 1), np.flatnonzero(d == -1))]


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def fcd_table(path: Path, t_from: float, t_to: float) -> dict[str, np.ndarray]:
    """Long-format (t, id, x, y) of an FCD export for t_from <= t < t_to (raw SUMO coordinates)."""
    t, ids, x, y = [], [], [], []
    now = None
    for ev, el in ET.iterparse(str(path), events=("start", "end")):
        if ev == "start" and el.tag == "timestep":
            now = round(float(el.get("time")), 4)
        elif ev == "end" and el.tag == "vehicle":
            if t_from - 1e-6 <= now < t_to - 1e-6:
                t.append(now); ids.append(el.get("id")); x.append(float(el.get("x"))); y.append(float(el.get("y")))
            el.clear()
        elif ev == "end" and el.tag == "timestep":
            el.clear()
    return {"t": np.array(t), "id": np.array(ids), "x": np.array(x), "y": np.array(y)}


def fcd_compare(a: dict, b: dict) -> dict:
    """Exact comparison of two FCD tables (same rows, same order, positions to the printed digit)."""
    if len(a["t"]) != len(b["t"]):
        return {"identical": False, "rows": [int(len(a["t"])), int(len(b["t"]))]}
    ids_eq = bool(np.array_equal(a["id"], b["id"]) and np.array_equal(a["t"], b["t"]))
    dx = float(np.max(np.abs(a["x"] - b["x"]))) if len(a["t"]) else 0.0
    dy = float(np.max(np.abs(a["y"] - b["y"]))) if len(a["t"]) else 0.0
    return {"identical": ids_eq and dx == 0.0 and dy == 0.0, "rows": int(len(a["t"])), "ids_equal": ids_eq,
            "max_abs_dx_m": dx, "max_abs_dy_m": dy}


def write_veins_cfg(sumo: str, d: Path, t0: float, t_end: float) -> None:
    """veins.sumocfg = run.sumocfg (full warm-up from t = 0) + FCD output from t0; run it once headless
    to produce fcd_veins.xml for the identity check.

    Resuming from a saved SUMO state was tried and rejected (2026-10-18): with
    --save-state.rng and --save-state.precision 17 the resumed run matched the reference for 9.5 s,
    then one vehicle diverged by 0.22 m (rural d=20 s=200). Veins therefore steps SUMO through the
    warm-up; applications stay silent until their vehicle's first active step."""
    cfg = ET.parse(d / "run.sumocfg").getroot()
    cfg.find("time").find("end").set("value", f"{t_end + 1.0:.1f}")
    out = ET.SubElement(cfg, "output")
    ET.SubElement(out, "fcd-output", value="fcd_veins.xml")
    dev = ET.SubElement(cfg, "fcd_device")
    ET.SubElement(dev, "device.fcd.begin", value=f"{t0:.1f}")
    ET.SubElement(dev, "device.fcd.period", value="0.1")
    ET.ElementTree(cfg).write(d / "veins.sumocfg")
    subprocess.run([sumo, "-c", "veins.sumocfg", "--no-step-log", "true", "--no-warnings", "true"],
                   cwd=d, check=True, capture_output=True)


def veins_params(scenario: str, phy, net_xml: Path) -> dict:
    """Veins analogue-model parameters for the SAME nominal physics as the custom PHY (no calibration):
    BreakpointPathlossModel with the custom dual-slope exponents and breakpoint, L01 = the custom
    reference loss at 1 m (free space) minus both antenna gains (Veins antennas are isotropic here), L02 continuous at the
    breakpoint; NakagamiFading with the custom m. Not representable in Veins 5.3 and therefore absent:
    log-normal shadowing, the beacon-load DCC. maxInterfDist: mean received power -110 dBm."""
    assert phy.reference_distance_m == 1.0, "Veins' breakpoint model has a 1 m reference"
    l01 = phy.reference_loss_db - phy.tx_gain_dbi - phy.rx_gain_dbi
    bp, a1, a2 = phy.breakpoint_distance_m, phy.path_loss_exponent, phy.path_loss_exponent_far
    l02 = l01 + 10 * a1 * math.log10(bp)
    budget = phy.tx_power_dbm + 110.0                       # dB of loss to reach -110 dBm
    d_int = bp * 10 ** ((budget - l02) / (10 * a2)) if budget > l02 else 10 ** ((budget - l01) / (10 * a1))
    loc = ET.parse(net_xml).getroot().find("location")
    x0, y0, x1, y1 = (float(v) for v in loc.get("convBoundary").split(","))
    return {"L01": l01, "L02": l02, "alpha1": a1, "alpha2": a2, "breakpointDistance": bp,
            "nakagami_m": float(phy.nakagami_m), "centerFrequency": phy.frequency_hz,
            "txPower_mW": 10 ** (phy.tx_power_dbm / 10), "noiseFloor_dBm": phy.noise_dbm,
            "minPowerLevel_dBm": phy.sensitivity_dbm, "maxInterfDist_m": round(d_int, 1),
            "playgroundSizeX_m": math.ceil(x1 - min(x0, 0) + 200), "playgroundSizeY_m": math.ceil(y1 - min(y0, 0) + 200)}


def export(scenario: str, density: float, seed: int, out: Path = OUT) -> Path:
    scfg = load_scenario(scenario)
    phy_cfg = load_yaml("phy.yaml")
    canon = get_trace(scfg, density, seed, weather="clear", backend="sumo", phy_cfg=phy_cfg)

    sf, hf = weather_mobility_factors("clear", phy_cfg)
    resolved, tools = resolve_backend("sumo")
    key = trace_cache_key(scfg, density, seed, resolved.value, sf, hf, None)
    regen = generate_sumo_trace(scfg, density, seed, tools=tools, speed_factor=sf, tag=f"veins_{key}",
                                keep_fcd=True)
    same = (canon.x.shape == regen.x.shape and np.array_equal(canon.active, regen.active)
            and np.array_equal(canon.vehicle_ids, regen.vehicle_ids)
            and np.array_equal(np.where(canon.active, canon.x, 0), np.where(regen.active, regen.x, 0))
            and np.array_equal(np.where(canon.active, canon.y, 0), np.where(regen.active, regen.y, 0)))
    if not same:
        raise SystemExit(f"{scenario} d={density:g} s={seed}: regenerated SUMO trace differs from the "
                         "cached trace -- refusing to export a non-identical scenario")
    work = sorted(BUILD_DIR.glob(f"{scfg['name']}_d{density:g}_s{seed}_veins_{key}_p*"),
                  key=lambda p: p.stat().st_mtime)[-1]

    _, res = run_single(RunSpec(scenario=scenario, density_veh_km_lane=density, seed=seed,
                                policy="flooding", backend="sumo"), return_result=True)
    dt = float(canon.dt)
    warmup = float(canon.meta["warmup_s"])
    t0 = round(math.ceil(round(warmup / dt, 6)) * dt, 4)      # first FCD sample parse_fcd keeps
    d = out / f"{scenario}_d{density:g}_s{seed}"
    if d.exists():
        shutil.rmtree(d)
    d.mkdir(parents=True)
    files = {}
    for f in work.iterdir():
        if f.suffix in (".xml", ".sumocfg", ".cfg") and f.name != "fcd.xml":
            shutil.copy2(f, d / f.name)
            files[f.name] = sha(d / f.name)
    ref = fcd_table(work / "fcd.xml", t0, t0 + canon.n_steps * dt)
    if len(np.unique(ref["t"])) != canon.n_steps:
        raise SystemExit(f"reference FCD has {len(np.unique(ref['t']))} steps, trace {canon.n_steps}")
    np.savez_compressed(d / "fcd_ref.npz", **ref)
    write_veins_cfg(tools.sumo, d, t0, t0 + canon.n_steps * dt)
    chk = fcd_compare(ref, fcd_table(d / "fcd_veins.xml", t0, t0 + canon.n_steps * dt))
    if not chk["identical"]:
        raise SystemExit(f"state-resumed SUMO run differs from the reference FCD: {chk}")
    (d / "fcd_veins.xml").unlink()
    radio = phy_cfg["radio"] | {"receiver": phy_cfg["receiver"],
                                "path_loss": {k: (v.get(scenario) if isinstance(v, dict) else v)
                                              for k, v in phy_cfg["path_loss"].items()},
                                "fading_m": phy_cfg["fading"]["m"][scenario],
                                "corner_loss_db": phy_cfg["nlos"]["corner_loss_db"][scenario],
                                "beacon": {k: v for k, v in phy_cfg["mac"].items() if "beacon" in k or "dcc" in k},
                                "frame_duration_s": res.mac.frame_duration_s}
    net_xml = next(d.glob("*.net.xml"))
    bundle_veins = veins_params(scenario, res.phy, net_xml)
    # Beacon generation is application traffic, specified like the dissemination policy: the custom
    # MAC's DCC rule, rate = clip(target / (n * T_b), min_hz, max_hz) with n = active vehicles within
    # the carrier-sense range (sim/mac.py effective_beacon_hz), reproduced per beacon in Veins.
    m = res.mac
    bundle_veins.update({"cs_range_m": float(res.meta["cs_range_m"]), "beacon_duration_s": m.beacon_duration_s,
                         "beacon_hz": m.background_beacon_hz if m.background_beacon_enabled else 0.0,
                         "dcc_enabled": bool(m.dcc_enabled), "dcc_target_cbr": m.dcc_target_cbr,
                         "dcc_min_beacon_hz": m.dcc_min_beacon_hz, "beacon_bytes": m.background_beacon_bytes,
                         # channel access: the custom MAC gives every hazard transmitter of an epoch a
                         # uniform backoff slot in [0, CWmin] (sim/mac.py draw_backoff_slots). 802.11 sends
                         # a frame that finds the medium idle after AIFS WITHOUT backoff, so epoch-aligned
                         # relays would all start together in Veins; the app applies the same draw.
                         "cw_slots": int(m.cw_slots), "slot_time_s": float(m.slot_time_s)})
    bundle = {
        "veins": bundle_veins,
        "scenario": scenario, "density": density, "seed": seed, "dt": dt, "t0_sumo_s": t0, "warmup_s": warmup, "fcd_check_windows": chk,
        "n_steps": int(canon.n_steps), "sumocfg": "veins.sumocfg", "files": files,
        "vehicles": [{"index": i, "sumo_id": str(v), "active": intervals(canon.active[:, i])}
                     for i, v in enumerate(canon.vehicle_ids)],
        "origin": {"index": int(res.origin_index), "step": int(res.origin_step),
                   "sumo_id": str(canon.vehicle_ids[res.origin_index]) if res.origin_index >= 0 else None},
        "comm_range_m": float(res.meta["comm_range_m"]),
        "settings": {"max_hops": 32, "message_ttl_s": 60.0},
        "radio": radio,
        "custom_flooding_reference": {"n_transmissions": res.n_transmissions,
                                      "n_informed": int(res.n_informed)},
        "provenance": stamp("revision5/veins/export", {"scenario": scenario, "density": density},
                            seeds=[seed], n_runs=1),
    }
    (d / "bundle.json").write_text(json.dumps(bundle, indent=1, default=str))
    return d


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("scenario")
    ap.add_argument("density", type=float)
    ap.add_argument("seeds", type=int, nargs="+")
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args(argv)
    for s in a.seeds:
        print(export(a.scenario, a.density, s, a.out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
