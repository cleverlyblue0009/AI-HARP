"""Revision-9 manifest: adds the revision-9 outputs that exist to results/MANIFEST.md and results/manifest.json.

    python -m experiments.revision9.manifest

Entries of earlier revisions are kept exactly as they are (everything before the "## Revision 9" heading and every
manifest.json entry outside results/revision9/); earlier revision-9 entries are replaced. Outputs that do not exist yet
are listed with "exists": false and no hash.
"""

from __future__ import annotations

import json

from common.config import PROJECT_ROOT
from experiments.revision8.manifest import digest

R = PROJECT_ROOT / "results"
R9 = "results/revision9/"
E = "experiments/revision9/"
GATES = [R9 + "gates_runs_slice{0..19}of20.csv"]
SPEC = [
    (R9 + "miss_targets.json", E + "gates.py", "python -m experiments.revision9.gates analyse",
     GATES + ["results/coverage_targets.json", "training-pool seeds 100-131"]),
    (R9 + "gates.json", E + "gates.py", "python -m experiments.revision9.gates analyse",
     GATES + ["results/coverage_targets.json", R9 + "miss_targets.json"]),
    (R9 + "train/", "agents/train_structured.py",
     "python -m agents.train_structured --arm {plain,rand} --seed {0..4} --miss-targets results/revision9/miss_targets.json",
     ["results/coverage_targets.json", "results/revision8/warm_start.json", R9 + "miss_targets.json",
      "training-pool traces 100-131"]),
    (R9 + "train_summary.json", E + "train_summary9.py", "python -m experiments.revision9.train_summary9",
     [R9 + "train/*/history.jsonl", R9 + "train/*/run_meta.json"]),
    (R9 + "veins/h6_rows.jsonl", E + "analysis/veins9.py", "python -m experiments.revision9.analysis.veins9 assemble h6",
     [R9 + "veins/h6/<cell>_s<seed>/ (20 runner shards, ci9.py h6)"]),
    (R9 + "veins/c1_rows.jsonl", E + "analysis/veins9.py", "python -m experiments.revision9.analysis.veins9 assemble c1",
     [R9 + "veins/c1/<cell>_s<seed>/ (20 runner shards, ci9.py c1)"]),
    (R9 + "analysis/h6.json", E + "analysis/veins9.py", None,
     [R9 + "veins/h6_rows.jsonl", "results/revision8/veins_thresholds.json"]),
    (R9 + "analysis/c1.json", E + "analysis/veins9.py", None,
     [R9 + "veins/c1_rows.jsonl", "results/revision8/veins/h5B_rows.jsonl", "results/revision8/veins_thresholds.json"]),
    (R9 + "analysis/s1.json", E + "analysis/veins9.py", None,
     [R9 + "veins/h6_rows.jsonl", R9 + "veins/c1_rows.jsonl", "results/revision8/veins_thresholds.json"]),
    (R9 + "runs/struct9_plain__SEL__headline__default__fallback.csv", E + "sweep9.py",
     "python -m experiments.revision9.sweep9 merge plain SEL", [R9 + "train/plain_s*/theta.json"]),
    (R9 + "runs/struct9_plain__EVAL__headline__default__fallback.csv", E + "sweep9.py",
     "python -m experiments.revision9.sweep9 merge plain EVAL", [R9 + "train/plain_s*/theta.json"]),
    (R9 + "runs/struct9_rand__SEL__headline__default__fallback.csv", E + "sweep9.py",
     "python -m experiments.revision9.sweep9 merge rand SEL", [R9 + "train/rand_s*/theta.json"]),
    (R9 + "runs/struct9_rand__EVAL__headline__default__fallback.csv", E + "sweep9.py",
     "python -m experiments.revision9.sweep9 merge rand EVAL", [R9 + "train/rand_s*/theta.json"]),
    (R9 + "analysis/s2.json", E + "analysis/s2.py", None,
     [R9 + "runs/struct9_{plain,rand}__{SEL,EVAL}__headline__default__fallback.csv",
      "results/revision5/runs/classical__{SEL,EVAL}__grid24__default__fallback.csv",
      "results/revision5/runs/rule__{SEL,EVAL}__grid24__default__fallback.csv", "results/revision5/thresholds.json"]),
]
MARK = "## Revision 9"


def main(argv=None) -> int:
    man = json.loads((R / "manifest.json").read_text(encoding="utf-8"))
    keep = [o for o in man["outputs"] if not o["output"].startswith(R9)]
    new = []
    for name, script, cmd, src in SPEC:
        p = PROJECT_ROOT / name
        pv = {}
        if p.suffix == ".json" and p.exists():
            pv = json.loads(p.read_text(encoding="utf-8")).get("provenance", {}) or {}
        new.append({"output": name, "exists": p.exists(), "script": script, "command": cmd or pv.get("command"),
                    "commit": pv.get("git_commit"), "config_hash": pv.get("config_hash"), "generated": pv.get("generated"),
                    "sources": src, "sha256": digest(p)})
    man["outputs"] = keep + new
    (R / "manifest.json").write_text(json.dumps(man, indent=1) + "\n", encoding="utf-8", newline="\n")
    text = (R / "MANIFEST.md").read_text(encoding="utf-8").split(MARK)[0].rstrip() + "\n\n"
    lines = [MARK, "", "Generated by `python -m experiments.revision9.manifest`. Regenerate the analysis outputs with",
             "`reproduce_revision9.sh` (or `.ps1`). Pre-registration: `results/revision9/ADDENDUM.md` (post-hoc motivated).",
             "Runner work (gates, training, Veins, S2) ran on GitHub-hosted runners; outputs on branch `r9-ci`.", "",
             "| Output | Script / command | Commit | Config hash | Source rows |", "|---|---|---|---|---|"]
    for o in new:
        src = "<br>".join(f"`{s}`" for s in o["sources"]) or "–"
        out = f"`{o['output']}`" + ("" if o["exists"] else " *(not yet)*")
        lines.append(f"| {out} | `{o['command']}` | {(o['commit'] or '–')[:12]} | {o['config_hash'] or '–'} | {src} |")
    (R / "MANIFEST.md").write_text(text + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(R / "MANIFEST.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
